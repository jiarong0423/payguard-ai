"""Deterministic evidence PDF built from the fields of a reviewed synthetic draft.

Standard library only. The bytes depend on the input alone: no clock, no random id, no producer metadata.
The renderer refuses text that looks like an e-mail address, a local path or a full PayPal dispute id.
"""

import hashlib
import re
import textwrap

FOOTER = "Synthetic Sandbox evidence generated by PayGuard; not a real merchant case"
MAX_PAGES = 2
LINES_PER_PAGE = 46
WRAP_WIDTH = 88
_FORBIDDEN = (
    re.compile(r"@"),
    re.compile("/" + "Users/"),  # built from two parts: the public-text gate rejects a literal local path
    re.compile(r"PP-[A-Z0-9]"),
    re.compile(r"(?i)api[_-]?key|secret|password|bearer\s"),
)
_SHA256 = re.compile(r"[a-f0-9]{64}\Z")


class EvidencePdfError(ValueError):
    """Fixed-code failure that never echoes caller data."""


def _fail(code):
    raise EvidencePdfError(code)


def _text(value, fallback="not provided"):
    if value is None or value == "":
        return fallback
    if type(value) is not str:
        value = str(value)
    return "".join(ch if 32 <= ord(ch) < 127 else "?" for ch in value)


def _escape(line):
    return line.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def _money(amount):
    if type(amount) is not dict:
        return "not provided"
    return _text(amount.get("currency_code")) + " " + _text(amount.get("value"))


def fields_from_case(case_ref, case, review_completed_at=None, review_zip_sha256=None):
    """Pick the synthetic fields the PDF shows from a prepared dispute case. Identifiers other than the masked
    case reference are left out on purpose."""
    snapshot = case.get("provider_snapshot") or {}
    proofs = case.get("proof_records") or []
    proof_by_request = {}
    for proof in proofs:
        proof_by_request.setdefault(proof.get("request_id"), proof)
    requested = []
    for row in snapshot.get("evidences") or []:
        proof = proof_by_request.get(row.get("request_id"))
        requested.append({"evidence_type": row.get("evidence_type"), "mandatory": bool(row.get("mandatory")),
                          "provided": proof is not None})
    first = next((p for p in proofs if isinstance(p.get("proof_fields"), dict)), None)
    tracking = dict(first["proof_fields"]) if first else {}
    return {
        "case_ref": case_ref,
        "reason": snapshot.get("reason"),
        "status": snapshot.get("status"),
        "amount": case.get("dispute_amount"),
        "due": snapshot.get("seller_response_due_date"),
        "requested": requested,
        "carrier": tracking.get("carrier_name"),
        "tracking_number": tracking.get("tracking_number"),
        "delivery_status": tracking.get("delivery_status"),
        "destination_match": tracking.get("destination_match_status"),
        "shipped_at": tracking.get("shipped_at"),
        "delivered_at": tracking.get("delivered_at") or case.get("delivered_at"),
        "timeline": [("Order created", case.get("order_created_at")),
                     ("Delivered", case.get("delivered_at")),
                     ("Dispute opened", case.get("opened_at")),
                     ("Seller response due", snapshot.get("seller_response_due_date"))],
        "review_completed_at": review_completed_at,
        "review_zip_sha256": review_zip_sha256,
    }


def _lines(fields):
    if type(fields) is not dict:
        _fail("evidence_pdf_input_invalid")
    out = ["PayGuard - Delivery evidence summary (synthetic)", ""]
    out.append("Case reference (masked): " + _text(fields.get("case_ref")))
    out.append("Dispute reason: " + _text(fields.get("reason")))
    out.append("Dispute status: " + _text(fields.get("status")))
    out.append("Disputed amount: " + _money(fields.get("amount")))
    out.append("Seller response due (UTC): " + _text(fields.get("due")))
    out += ["", "Evidence requested"]
    for row in fields.get("requested") or []:
        out.append("  - " + _text(row.get("evidence_type")) + " (" + ("mandatory" if row.get("mandatory") else "optional")
                   + "): " + ("provided" if row.get("provided") else "NOT provided"))
    if not fields.get("requested"):
        out.append("  - none listed")
    out += ["", "Provenance: seller-supplied, unverified. PayGuard did not verify these fields with the carrier.",
            "", "Gaps"]
    gaps = ["  - " + _text(row.get("evidence_type")) + ": no record provided"
            for row in fields.get("requested") or [] if not row.get("provided")]
    if not fields.get("shipped_at"):
        gaps.append("  - Shipped-at time: not recorded in the draft")
    out += gaps or ["  - none found in the draft"]
    out += ["", "Tracking"]
    out.append("  Carrier: " + _text(fields.get("carrier")))
    out.append("  Tracking number: " + _text(fields.get("tracking_number")))
    out.append("  Shipped at (UTC): " + _text(fields.get("shipped_at"), "not recorded in the draft"))
    out.append("  Delivered at (UTC): " + _text(fields.get("delivered_at")))
    out.append("  Delivery status: " + _text(fields.get("delivery_status")))
    out.append("  Destination match: " + _text(fields.get("destination_match")))
    out += ["", "Timeline (UTC)"]
    for label, moment in fields.get("timeline") or []:
        out.append("  " + _text(label) + ": " + _text(moment))
    out.append("")
    completed = fields.get("review_completed_at")
    if completed:
        out.append("HUMAN REVIEW COMPLETED - " + _text(completed))
    else:
        out.append("HUMAN REVIEW: not yet completed when this file was generated; nothing is sent until a person approves.")
    digest = fields.get("review_zip_sha256")
    if digest is not None:
        if type(digest) is not str or _SHA256.fullmatch(digest) is None:
            _fail("evidence_pdf_input_invalid")
        out.append("Review ZIP SHA-256: " + digest)
    wrapped = []
    for line in out:
        wrapped += textwrap.wrap(line, WRAP_WIDTH, subsequent_indent="    ", drop_whitespace=False) or [""]
    return wrapped


def build_evidence_pdf(fields):
    """Return the PDF bytes for ``fields`` (see ``fields_from_case``); identical input gives identical bytes."""
    body = _lines(fields)
    capacity = LINES_PER_PAGE * MAX_PAGES - 2
    if len(body) > capacity:
        _fail("evidence_pdf_too_long")
    all_text = "\n".join(body) + "\n" + FOOTER
    if any(pattern.search(all_text) for pattern in _FORBIDDEN):
        _fail("evidence_pdf_forbidden_text")
    pages = [body[i:i + LINES_PER_PAGE] for i in range(0, len(body), LINES_PER_PAGE)] or [[]]
    pages[-1] = pages[-1] + ["", FOOTER] if len(pages[-1]) + 2 <= LINES_PER_PAGE else pages[-1]
    if pages[-1][-1] != FOOTER:
        pages.append(["", FOOTER])
    if len(pages) > MAX_PAGES:
        _fail("evidence_pdf_too_long")
    objects = {}
    kids = []
    next_id = 4
    for index, page_lines in enumerate(pages):
        page_id, content_id = next_id, next_id + 1
        next_id += 2
        ops = ["BT", "/F1 10 Tf", "14 TL", "50 800 Td"]
        for line in page_lines:
            ops.append("(" + _escape(line) + ") Tj T*")
        ops.append("ET")
        stream = "\n".join(ops).encode("ascii")
        objects[content_id] = b"<< /Length %d >>\nstream\n" % len(stream) + stream + b"\nendstream"
        objects[page_id] = (b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] "
                            b"/Resources << /Font << /F1 3 0 R >> >> /Contents %d 0 R >>" % content_id)
        kids.append(b"%d 0 R" % page_id)
    objects[1] = b"<< /Type /Catalog /Pages 2 0 R >>"
    objects[2] = b"<< /Type /Pages /Kids [" + b" ".join(kids) + b"] /Count %d >>" % len(kids)
    objects[3] = b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>"
    out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = {}
    for number in sorted(objects):
        offsets[number] = len(out)
        out += b"%d 0 obj\n" % number + objects[number] + b"\nendobj\n"
    xref_at = len(out)
    count = max(objects) + 1
    out += b"xref\n0 %d\n" % count + b"0000000000 65535 f \n"
    for number in range(1, count):
        out += b"%010d 00000 n \n" % offsets[number]
    out += b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (count, xref_at)
    return bytes(out)


def evidence_pdf_for_case(case_ref, case, review_completed_at=None, review_zip_sha256=None):
    return build_evidence_pdf(fields_from_case(case_ref, case, review_completed_at, review_zip_sha256))


def sha256_hex(content):
    return hashlib.sha256(content).hexdigest()
